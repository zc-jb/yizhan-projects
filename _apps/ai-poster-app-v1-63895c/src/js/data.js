/* ============ 为每套模板追加「联系方式 + 二维码」角标 ============
   作为独立图层追加在顶层：可拖动、可编辑内容、可删除。
   二维码由本地内置库离线生成（不联网也可用）；联系方式为普通文字，双击即改。 */
const makeQrSrc = (text, size = 300, dark = '#000000', light = '#ffffff') => {
  const cv = document.createElement('canvas');
  try {
    const qr = qrcode(0, 'M'); // 0 = 自动选择版本
    qr.addData(String(text ?? ''));
    qr.make();
    const n = qr.getModuleCount(), m = 4; // m = 静默区(模块数)
    const px = Math.max(2, Math.floor(size / (n + m * 2)));
    const tot = (n + m * 2) * px;
    cv.width = cv.height = tot;
    const c = cv.getContext('2d');
    c.fillStyle = light; c.fillRect(0, 0, tot, tot);
    c.fillStyle = dark;
    for (let r = 0; r < n; r++) for (let col = 0; col < n; col++)
      if (qr.isDark(r, col)) c.fillRect((col + m) * px, (r + m) * px, px, px);
  } catch (e) {
    cv.width = cv.height = 64;
    const c = cv.getContext('2d');
    c.fillStyle = light; c.fillRect(0, 0, 64, 64);
    c.fillStyle = '#999'; c.font = '14px sans-serif'; c.textAlign = 'center';
    c.fillText('QR', 32, 38);
  }
  return cv.toDataURL('image/png');
};
